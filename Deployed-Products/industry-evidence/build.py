"""Build evidence-log.md and ../industry-matrix.html from evidence.json + link_check.json.

Run:  python3 build.py
Validates the data first; fails loudly if any incident is malformed.
"""
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
DATA = json.loads((HERE / "evidence.json").read_text())
LINKS = json.loads((HERE / "link_check.json").read_text())
STATUS = {r["url"]: r["status"] for r in LINKS["results"]}


def validate():
    area_ids = {a["id"] for a in DATA["areas"]}
    ids = [i["id"] for i in DATA["incidents"]]
    assert len(ids) == len(set(ids)), "duplicate incident IDs"
    for i in DATA["incidents"]:
        assert i["product"] in DATA["products"], f"{i['id']}: unknown product"
        assert i["area"] in area_ids, f"{i['id']}: unknown area"
        assert i["sources"], f"{i['id']}: no sources"
        assert i["confidence"] in {"high", "medium-high", "medium"}, f"{i['id']}: bad confidence"
        for _, url, kind in i["sources"]:
            assert kind in {"primary", "secondary"}, f"{i['id']}: bad source kind"
            assert url in STATUS, f"{i['id']}: url not link-checked: {url}"


def link_badge(url):
    s = STATUS.get(url)
    return "200 OK" if s == 200 else f"{s} (site blocks automated checks; found via search)"


def build_md():
    area = {a["id"]: a for a in DATA["areas"]}
    codes = Counter(str(r["status"]) for r in LINKS["results"])
    out = [
        "# GenAI Production Incidents: Evidence Log",
        "",
        f"**Verified on:** {DATA['verified_on']}  ",
        f"**Method:** {DATA['method']}  ",
        f"**Link check:** {len(LINKS['results'])} source URLs checked at {LINKS['checked_at']}: "
        + ", ".join(f"{n} × HTTP {c}" for c, n in codes.items())
        + ". HTTP 200 proves the page exists. The claim itself was checked against search-result summaries of these sources.",
        "",
        "> These are **public** incidents, as reported. Lawsuits are allegations unless a ruling is noted. "
        "Confidence: **high** = primary source or several consistent major outlets; "
        "**medium-high** = consistent coverage but mainly one party's account; **medium** = current status not verified.",
        "",
        "## Matrix: product × area",
        "",
        "| Product | " + " | ".join(a["icon"] + " " + a["name"] for a in DATA["areas"]) + " |",
        "|---" * (len(DATA["areas"]) + 1) + "|",
    ]
    for p in DATA["products"]:
        cells = []
        for a in DATA["areas"]:
            hits = [i["id"] for i in DATA["incidents"] if i["product"] == p and i["area"] == a["id"]]
            cells.append(", ".join(hits) if hits else "·")
        out.append(f"| {p} | " + " | ".join(cells) + " |")
    out += ["", "`·` = no incident logged here. It does **not** mean the product is free of that risk.", "", "## Incidents", ""]
    for i in sorted(DATA["incidents"], key=lambda x: x["date"]):
        a = area[i["area"]]
        out += [
            f"### {i['id']} · {i['product']} · {i['title']}",
            "",
            "| Field | Value |", "|---|---|",
            f"| Date | {i['date']} |",
            f"| Area | {a['icon']} {a['name']} |",
            f"| What happened | {i['what']} |",
            f"| Impact | {i['impact']} |",
            f"| Confidence | **{i['confidence']}** |",
            f"| Notes / discrepancies | {i['notes']} |",
            "",
            "| Source | Type | Link check |", "|---|---|---|",
        ]
        out += [f"| [{t}]({u}) | {k} | {link_badge(u)} |" for t, u, k in i["sources"]]
        out.append("")
    out += ["## Key areas and what to teach", "", "| Area | Lesson | Where our labs touch it |", "|---|---|---|"]
    out += [f"| {a['icon']} {a['name']} | {a['lesson']} | {a['our_lab']} |" for a in DATA["areas"]]
    out += ["", "*Generated by `build.py` from `evidence.json`. Edit the JSON and rebuild, never the output.*", ""]
    (HERE / "evidence-log.md").write_text("\n".join(out))


def build_html():
    tpl = (HERE / "matrix_template.html").read_text()
    payload = dict(DATA, link_status=STATUS, checked_at=LINKS["checked_at"])
    html = tpl.replace("/*__DATA__*/null", json.dumps(payload, ensure_ascii=False))
    (HERE.parent / "industry-matrix.html").write_text(html)


if __name__ == "__main__":
    validate()
    build_md()
    build_html()
    print(f"OK: {len(DATA['incidents'])} incidents, {len(DATA['products'])} products, {len(DATA['areas'])} areas")
